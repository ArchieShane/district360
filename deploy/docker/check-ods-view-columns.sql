       CASE e.kind
           WHEN 'text' THEN '文本（varchar / text）'
           WHEN 'num'  THEN '数值（integer / numeric / double）'
           WHEN 'date' THEN '日期或时间（date / timestamp）'
           ELSE '任意类型'
